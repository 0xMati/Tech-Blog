function Get-ConditionSummary {
    param([object]$Rule)

    if (-not $Rule.ConditionSupported) { return 'Manual review required' }
    if (@($Rule.Conditions).Count -eq 0) { return 'Always' }
    $parts = foreach ($selector in @($Rule.Conditions)) {
        $claimType = Get-SelectorClaimType -Selector $selector
        $claimName = if ($claimType) { $claimType.Split('/')[-1] } elseif ($selector.Body -eq '') { 'any claim' } else { $selector.Body }
        $predicates = @($selector.Predicates | Where-Object Field -ne 'Type' | ForEach-Object {
            "$($_.Field) $($_.Operator) '$($_.Expected)'"
        })
        $detail = if ($predicates.Count -gt 0) { "$claimName ($($predicates -join ', '))" } else { $claimName }
        if ($selector.Negated) { "NOT EXISTS $detail" } else { "EXISTS $detail" }
    }
    return (@($parts) -join ' AND ')
}

function Get-ActionSummary {
    param([object]$Rule)

    $verb = if ($Rule.ActionVerb) { $Rule.ActionVerb.ToUpperInvariant() } else { 'UNKNOWN' }
    $inputs = @($Rule.InputClaimTypes) -join ', '
    $outputs = @($Rule.OutputClaimTypes) -join ', '
    switch ($Rule.ActionKind) {
        'StaticClaim'    { return "$verb static claim: $outputs='$($Rule.OutputClaimValue)'" }
        'PassThrough'    { return "$verb pass-through: $inputs" }
        'CopyClaimValue' { return "$verb copy value: $inputs -> $outputs" }
        'RegexTransform' { return "$verb RegExReplace: $inputs -> $outputs" }
        'AttributeStore' { return "$verb from store '$($Rule.AttributeStore)': $inputs -> $outputs (manual reconstruction)" }
        default          { return 'Manual review required' }
    }
}

