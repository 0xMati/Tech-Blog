function Resolve-AdfsTransactionTarget {
    param(
        [object]$Transaction,
        [object[]]$Configuration
    )

    $observedValue = ConvertTo-AdfsMeaningfulText -Value $Transaction.RelyingParty
    if (-not $observedValue) {
        if (@($Configuration).Count -eq 1) {
            return [pscustomobject]@{ Status = 'MAPPED'; Configuration = $Configuration[0]; MatchMethod = 'Single selected RP'; ObservedValue = $null }
        }
        return [pscustomobject]@{ Status = 'UNMAPPED'; Configuration = $null; MatchMethod = 'No RP evidence'; ObservedValue = $null }
    }

    $exactCandidates = @($Configuration | Where-Object {
        if ($observedValue -ieq [string]$_.Name) { return $true }
        foreach ($identifier in @($_.Identifier)) {
            if ($observedValue -ieq [string]$identifier) { return $true }
        }
        return $false
    })
    if ($exactCandidates.Count -eq 1) {
        return [pscustomobject]@{ Status = 'MAPPED'; Configuration = $exactCandidates[0]; MatchMethod = 'Exact name or identifier'; ObservedValue = $observedValue }
    }
    if ($exactCandidates.Count -gt 1) {
        return [pscustomobject]@{ Status = 'AMBIGUOUS'; Configuration = $null; MatchMethod = 'Exact identifier matched multiple RPs'; ObservedValue = $observedValue }
    }

    $observedUri = $null
    try {
        $observedUri = [uri]$observedValue
    } catch {
        Write-Verbose "Observed RP value is not an absolute URI: $observedValue"
    }
    if ($observedUri -and $observedUri.IsAbsoluteUri) {
        $observedAuthority = $observedUri.GetLeftPart([UriPartial]::Authority)
        $authorityCandidates = @($Configuration | Where-Object {
            foreach ($identifier in @($_.Identifier)) {
                try {
                    $identifierUri = [uri][string]$identifier
                    if ($identifierUri.IsAbsoluteUri -and $identifierUri.GetLeftPart([UriPartial]::Authority) -ieq $observedAuthority) {
                        return $true
                    }
                } catch {
                    Write-Verbose "Configured RP identifier is not an absolute URI: $identifier"
                }
            }
            return $false
        })
        if ($authorityCandidates.Count -eq 1) {
            return [pscustomobject]@{ Status = 'MAPPED'; Configuration = $authorityCandidates[0]; MatchMethod = 'Unique URI authority'; ObservedValue = $observedValue }
        }
        if ($authorityCandidates.Count -gt 1) {
            return [pscustomobject]@{ Status = 'AMBIGUOUS'; Configuration = $null; MatchMethod = 'URI authority matched multiple RPs'; ObservedValue = $observedValue }
        }
    }

    return [pscustomobject]@{ Status = 'UNMAPPED'; Configuration = $null; MatchMethod = 'No configuration match'; ObservedValue = $observedValue }
}

