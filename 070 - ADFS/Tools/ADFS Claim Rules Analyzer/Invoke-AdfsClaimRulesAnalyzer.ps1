function Get-AdfsClaimDisplayName {
    param([AllowNull()][string]$ClaimType)

    if ([string]::IsNullOrWhiteSpace($ClaimType)) { return 'Unknown claim' }
    $trimmedType = $ClaimType.TrimEnd('/')
    if ($trimmedType -match '[/#](?<name>[^/#]+)$') { return $Matches['name'] }
    if ($trimmedType -match ':(?<name>[^:]+)$') { return $Matches['name'] }
    return $trimmedType
}

