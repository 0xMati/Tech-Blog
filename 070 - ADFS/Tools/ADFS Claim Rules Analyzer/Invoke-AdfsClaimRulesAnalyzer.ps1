    $internalRules = @(ConvertFrom-AdfsClaimRuleSet -RelyingParty 'Test RP' -Identifiers @('urn:test') -RuleSetName IssuanceTransformRules -RuleSet $internalRuleSet)
    $internalResult = Invoke-AdfsRuleSetEvaluation -Rules $internalRules -Transaction $transformTransaction -EvaluationMode IssuanceTransform
    if ($internalResult.Evaluations[0].OutputObserved -ne 'INTERNAL ONLY') { throw 'add() output was incorrectly compared with event 500.' }
    if ($internalResult.Evaluations[2].Result -ne 'INDETERMINATE') { throw 'Attribute-store output was not propagated as a potential claim.' }

    Write-Ok 'Rule splitting: PASS'
    Write-Ok 'WAP + Windows user-agent: MATCH'
    Write-Ok 'Contradictory WAP location: NO MATCH'
    Write-Ok 'Missing evidence: INDETERMINATE'
