$collectLiveEvents = $IncludeEvents -or ($PSCmdlet.ParameterSetName -eq 'Live' -and -not $StaticOnly)
$isParameterlessLiveRun = $PSCmdlet.ParameterSetName -eq 'Live' -and $PSBoundParameters.Count -eq 0
$shouldOpenReport = $OpenReport -or $isParameterlessLiveRun

if ($StaticOnly -and ($IncludeEvents -or $EventLogPath)) {
    throw '-StaticOnly cannot be combined with -IncludeEvents or -EventLogPath.'
}
if ($NoHtml -and $OpenReport) {
    throw '-OpenReport cannot be combined with -NoHtml.'
}

Write-Host "ADFS Claim Rules Analyzer $script:ToolVersion" -ForegroundColor Cyan
Write-Section 'CONFIGURATION'
$auditLevel = 'Unknown'
if ($PSCmdlet.ParameterSetName -eq 'Offline') {
    Write-Info "Loading configuration snapshot: $ConfigurationPath"
    $configuration = @(Import-Clixml -LiteralPath $ConfigurationPath)
} else {
    Write-Info 'Reading relying party trusts from the local AD FS farm'
    $configuration = @(Get-LiveAdfsConfiguration -NamePatterns $RelyingPartyName)
    try {
        $auditLevel = [string](Get-AdfsProperties -ErrorAction Stop).AuditLevel
    } catch {
        Write-Verbose "Unable to read the AD FS audit level: $($_.Exception.Message)"
    }
}

if ($configuration.Count -eq 0) { throw 'No relying party trust matched the requested scope.' }

$ruleList = New-Object System.Collections.Generic.List[object]
foreach ($relyingParty in $configuration) {
    $authorizationRules = @(ConvertFrom-AdfsClaimRuleSet `
        -RelyingParty ([string]$relyingParty.Name) `
        -Identifiers @($relyingParty.Identifier) `
        -RuleSetName IssuanceAuthorizationRules `
        -RuleSet ([string]$relyingParty.IssuanceAuthorizationRules))
    foreach ($rule in $authorizationRules) { $ruleList.Add($rule) }
    $transformRules = @(ConvertFrom-AdfsClaimRuleSet `
        -RelyingParty ([string]$relyingParty.Name) `
        -Identifiers @($relyingParty.Identifier) `
        -RuleSetName IssuanceTransformRules `
        -RuleSet ([string]$relyingParty.IssuanceTransformRules))
    foreach ($rule in $transformRules) { $ruleList.Add($rule) }
    foreach ($rule in @(ConvertFrom-AdfsAccessControlPolicyAssignment -RelyingParty $relyingParty)) { $ruleList.Add($rule) }
}
$rules = $ruleList.ToArray()
$authorizationRuleCount = @($rules | Where-Object RuleSet -in @('IssuanceAuthorizationRules', 'AccessControlPolicy')).Count
$issuanceTransformRuleCount = @($rules | Where-Object RuleSet -eq 'IssuanceTransformRules').Count
Write-Ok "$($configuration.Count) relying party trust(s), $authorizationRuleCount authorization rule(s), $issuanceTransformRuleCount issuance transform rule(s)"
$accessControlPolicyCount = @($configuration | Where-Object {
    -not [string]::IsNullOrWhiteSpace([string](Get-ObjectPropertyValue -InputObject $_ -Name 'AccessControlPolicyName'))
}).Count
$analyzedAccessControlPolicyCount = @($rules | Where-Object RuleSet -eq 'AccessControlPolicy' | Select-Object -ExpandProperty RelyingParty -Unique).Count
$unsupportedAccessControlPolicyCount = $accessControlPolicyCount - $analyzedAccessControlPolicyCount
if ($unsupportedAccessControlPolicyCount -gt 0) {
    Write-WarnMessage "$unsupportedAccessControlPolicyCount relying party trust(s) use an Access Control Policy that this version does not parse."
} elseif ($rules.Count -eq 0) {
    Write-WarnMessage 'The selected relying party trusts expose no supported authorization rules.'
}

$events = @()
$correlatedActivities = @()
$transactions = @()
$ignoredActivityCount = 0
if ($collectLiveEvents -or $EventLogPath) {
    Write-Section 'AUDIT EVENTS'
    $servers = @()
    if ($collectLiveEvents) {
        $servers = @(Get-FarmServerNames -ExplicitServers $FarmServers)
        Write-Info "Farm nodes: $($servers -join ', ')"
        if ($auditLevel -ne 'Verbose') {
            Write-WarnMessage "AD FS AuditLevel is '$auditLevel'. Verbose is recommended for request headers and caller claims."
        }
    }
    $events = @(Get-AdfsAuditEvents -Servers $servers -Paths $EventLogPath -StartTime (Get-Date).AddDays(-$LookbackDays))
    $correlatedActivities = @(ConvertTo-AdfsTransactions -Events $events)
    $transactions = @($correlatedActivities | Where-Object { Test-IsPolicyRelevantTransaction -Transaction $_ })
    $ignoredActivityCount = $correlatedActivities.Count - $transactions.Count
    Write-Ok "$($events.Count) event(s) correlated into $($correlatedActivities.Count) activity transaction(s)"
    Write-Ok "$($transactions.Count) policy-relevant transaction(s); $ignoredActivityCount context-only activity transaction(s) excluded"
    if ($events.Count -gt 0 -and $correlatedActivities.Count -eq 0) {
        Write-WarnMessage 'Events were found but no Activity ID could be reconstructed. Verify AD FS Auditing configuration and EVTX integrity.'
    }
}

$evaluationList = New-Object System.Collections.Generic.List[object]
foreach ($transaction in $transactions) {
    $targetResolution = Resolve-AdfsTransactionTarget -Transaction $transaction -Configuration $configuration
    $transaction | Add-Member -NotePropertyName ObservedRelyingParty -NotePropertyValue $targetResolution.ObservedValue
    $transaction | Add-Member -NotePropertyName RelyingPartyMatch -NotePropertyValue $targetResolution.MatchMethod
    if ($targetResolution.Status -ne 'MAPPED') {
        $transaction | Add-Member -NotePropertyName ReconstructedDecision -NotePropertyValue $targetResolution.Status
        continue
    }

    $targetName = [string]$targetResolution.Configuration.Name
    $transaction.RelyingParty = $targetName
    $targetAuthorizationRules = @($rules | Where-Object {
        $_.RelyingParty -eq $targetName -and $_.RuleSet -in @('IssuanceAuthorizationRules', 'AccessControlPolicy')
    } | Sort-Object Index)
    $targetTransformRules = @($rules | Where-Object {
        $_.RelyingParty -eq $targetName -and $_.RuleSet -eq 'IssuanceTransformRules'
    } | Sort-Object Index)
    if ($targetAuthorizationRules.Count -eq 0) {
        $transaction | Add-Member -NotePropertyName ReconstructedDecision -NotePropertyValue 'NO RULES'
    } else {
        $authorizationResult = Invoke-AdfsRuleSetEvaluation -Rules $targetAuthorizationRules -Transaction $transaction -EvaluationMode Authorization
        $transaction | Add-Member -NotePropertyName ReconstructedDecision -NotePropertyValue $authorizationResult.Decision
        foreach ($evaluation in $authorizationResult.Evaluations) { $evaluationList.Add($evaluation) }
    }

    if ($targetTransformRules.Count -gt 0) {
        $transformResult = Invoke-AdfsRuleSetEvaluation -Rules $targetTransformRules -Transaction $transaction -EvaluationMode IssuanceTransform
        foreach ($evaluation in $transformResult.Evaluations) { $evaluationList.Add($evaluation) }
    }
}
$evaluations = $evaluationList.ToArray()

$ruleSummaries = @(Get-RuleSummaryRows -Rules $rules -Evaluations $evaluations)
$relyingPartySummaries = @(Get-RelyingPartySummaryRows -RelyingParties $configuration -Rules $rules)
$transactionSummaries = @(Get-TransactionSummaryRows -Transactions $transactions -Evaluations $evaluations)
$highFindings = @($rules | ForEach-Object { $_.Findings } | Where-Object Severity -eq 'High').Count
$warningFindings = @($rules | ForEach-Object { $_.Findings } | Where-Object Severity -eq 'Warning').Count
$manualReviewCount = @($rules | Where-Object { -not $_.ConditionSupported -or -not $_.ActionSupported }).Count + @(
    $relyingPartySummaries | Where-Object AuthorizationStatus -eq 'NOT ANALYZED - ACCESS CONTROL POLICY'
).Count
$indeterminateCount = @($evaluations | Where-Object Result -eq 'INDETERMINATE').Count

Write-Section 'SUMMARY'
Write-Host ("Relying parties: {0} | Authorization rules: {1} | Issuance transform rules: {2} | Access Control Policies: {3}" -f $configuration.Count, $authorizationRuleCount, $issuanceTransformRuleCount, $accessControlPolicyCount)
Write-Host ("High findings: {0} | Warnings: {1} | Manual review: {2}" -f $highFindings, $warningFindings, $manualReviewCount)
if ($transactions.Count -gt 0) {
    Write-Host ("Transactions: {0} | Evaluations: {1} | Indeterminate: {2}" -f $transactions.Count, $evaluations.Count, $indeterminateCount)
    $requestCoverage = @($transactions | Where-Object RequestContextComplete).Count
    $callerCoverage = @($transactions | Where-Object CallerClaimsComplete).Count
    Write-Host ("Audit evidence: request context {0}/{1} | caller claims {2}/{1}" -f $requestCoverage, $transactions.Count, $callerCoverage)
}

