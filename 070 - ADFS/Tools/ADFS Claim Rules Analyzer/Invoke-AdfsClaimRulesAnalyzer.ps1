<#
.SYNOPSIS
    Explains AD FS authorization and issuance transform claim rules.

.DESCRIPTION
    Reads IssuanceAuthorizationRules and IssuanceTransformRules from AD FS
    relying party trusts, parses common claim-rule constructs, detects risky or
    contradictory patterns, and correlates AD FS Auditing events by Activity ID.

    Authorization rules reconstruct PERMIT or DENY. Issuance transform rules
    reconstruct claim production separately and compare expected output types
    with claims observed in event 500.

    Evaluation uses three states: MATCH, NO MATCH, and INDETERMINATE. Missing
    audit evidence is never silently treated as proof that a condition failed.

    The script is read-only. It does not enable auditing or change AD FS policy.

.PARAMETER OutputPath
    Destination folder. Defaults to an output folder next to this script.

.PARAMETER RelyingPartyName
    Relying party names to include in live mode. Wildcards are supported.

.PARAMETER ConfigurationPath
    Offline configuration snapshot previously generated by this tool.

.PARAMETER IncludeEvents
    Explicitly read AD FS Auditing events from the Security log. Live mode now
    performs this collection by default; this switch is retained for compatibility.

.PARAMETER StaticOnly
    Analyze relying party configuration without collecting audit events.

.PARAMETER FarmServers
    Optional list of AD FS servers. If omitted, live mode discovers farm nodes.

.PARAMETER EventLogPath
    One or more exported Security EVTX files to analyze offline.

.PARAMETER LookbackDays
    Number of days retained from live Security logs or EVTX files. Default: 1.

.PARAMETER NoHtml
    Do not generate the HTML report.

.PARAMETER NoCsv
    Do not generate CSV exports. The CLIXML snapshot is still generated.

.PARAMETER NoJson
    Do not generate the JSON export.

.PARAMETER MaxHtmlTransactions
    Maximum number of recent transactions embedded in HTML. Default: 2000.
    Use 0 to include all transactions. CSV and JSON always retain all records.

.PARAMETER OpenReport
    Open the generated HTML report. A parameterless live run opens it by default;
    use this switch when other parameters are supplied.

.PARAMETER SelfTest
    Runs parser and evaluator tests without requiring the AD FS role.

.EXAMPLE
    .\Invoke-AdfsClaimRulesAnalyzer.ps1

    Runs the complete live analysis for the last 24 hours and opens the report.

.EXAMPLE
    .\Invoke-AdfsClaimRulesAnalyzer.ps1 -StaticOnly

    Analyzes relying party configuration without reading audit events.

.EXAMPLE
    .\Invoke-AdfsClaimRulesAnalyzer.ps1 -RelyingPartyName 'Microsoft Office 365 Identity Platform' -IncludeEvents

    Analyzes one relying party. -IncludeEvents is optional in live mode.

.EXAMPLE
    .\Invoke-AdfsClaimRulesAnalyzer.ps1 -ConfigurationPath .\Configuration.clixml -EventLogPath .\ADFS01-Security.evtx

    Performs offline analysis with a previously generated configuration snapshot.
#>


