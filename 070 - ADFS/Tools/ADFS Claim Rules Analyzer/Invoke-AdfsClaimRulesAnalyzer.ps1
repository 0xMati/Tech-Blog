        throw 'Invalid RegExReplace syntax was not detected during parsing.'
    }

    $internalRuleSet = @'
@RuleName = "Internal marker"
=> add(Type = "http://contoso.test/internal", Value = "true");

@RuleName = "Read external value"
c:[] => add(store = "Active Directory", types = ("http://contoso.test/fromstore"), query = ";department;{0}", param = c.Value);

@RuleName = "Use external value"
c:[Type == "http://contoso.test/fromstore"] => issue(Type = "http://contoso.test/final", Value = c.Value);
