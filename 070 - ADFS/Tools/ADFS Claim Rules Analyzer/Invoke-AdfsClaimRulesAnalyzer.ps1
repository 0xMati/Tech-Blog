function Get-SelectorClaimType {
    param([object]$Selector)

    $typePredicate = @($Selector.Predicates | Where-Object Field -eq 'Type' | Select-Object -First 1)
    if ($typePredicate.Count -eq 1 -and $typePredicate[0].Operator -eq '==') {
        return [string]$typePredicate[0].Expected
    }
    return $null
}

function Test-SelectorTypeSuffix {
    param(
        [object]$Selector,
        [string]$Suffix
    )

    $claimType = Get-SelectorClaimType -Selector $Selector
    return $claimType -and $claimType.EndsWith($Suffix, [System.StringComparison]::OrdinalIgnoreCase)
}

function ConvertFrom-AdfsClaimRuleSet {
    param(
        [string]$RelyingParty,
        [string[]]$Identifiers,
        [ValidateSet('IssuanceAuthorizationRules', 'IssuanceTransformRules')]
        [string]$RuleSetName,
        [AllowNull()][string]$RuleSet
    )

    $ruleBlocks = @(Split-AdfsRuleSet -RuleSet $RuleSet)
    $ruleIndex = 0
    $rules = New-Object System.Collections.Generic.List[object]

    foreach ($ruleBlock in $ruleBlocks) {
        $ruleIndex++
        $ruleName = if ($ruleBlock -match '(?im)^@RuleName\s*=\s*"([^"]+)"') { $Matches[1] } else { "Rule $ruleIndex" }
        $bodyLines = $ruleBlock -split "`r?`n" | Where-Object { $_ -notmatch '^\s*@Rule(?:Name|Template)\s*=' }
        $ruleBody = ($bodyLines -join "`n").Trim()
        $arrowPosition = $ruleBody.IndexOf('=>', [System.StringComparison]::Ordinal)
        $conditionText = if ($arrowPosition -ge 0) { $ruleBody.Substring(0, $arrowPosition).Trim() } else { $ruleBody }
        $actionText = if ($arrowPosition -ge 0) { $ruleBody.Substring($arrowPosition).Trim() } else { '' }

        $selectors = New-Object System.Collections.Generic.List[object]
        $selectorPattern = '(?is)(?<negated>\bNOT\s+)?(?:(?:EXISTS)\s*\(\s*)?(?:(?<alias>[A-Za-z_][A-Za-z0-9_]*)\s*:)?\s*\[(?<body>[^\]]*)\]\s*\)?'
        $selectorMatches = [regex]::Matches($conditionText, $selectorPattern)

        foreach ($selectorMatch in $selectorMatches) {
            $selectorBody = $selectorMatch.Groups['body'].Value.Trim()
            $predicates = New-Object System.Collections.Generic.List[object]
            $predicatePattern = '(?is)\b(?<field>Type|Value|Issuer|OriginalIssuer|ValueType)\s*(?<operator>==|!=|=~|!~)\s*"(?<expected>(?:\\.|[^"])*)"'

            foreach ($predicateMatch in [regex]::Matches($selectorBody, $predicatePattern)) {
                $predicates.Add([pscustomobject]@{
                    Field    = $predicateMatch.Groups['field'].Value
                    Operator = $predicateMatch.Groups['operator'].Value
                    Expected = $predicateMatch.Groups['expected'].Value.Replace('\"', '"')
                })
            }

            $selectorSupported = ($selectorBody -eq '') -or ($predicates.Count -gt 0)
            if ($selectorBody -match '(?i)COUNT\s*\(|store\s*=|query\s*=') { $selectorSupported = $false }
            $selectors.Add([pscustomobject]@{
                Negated    = $selectorMatch.Groups['negated'].Success
                Alias      = $selectorMatch.Groups['alias'].Value
                Body       = $selectorBody
                Predicates = $predicates.ToArray()
                Supported  = $selectorSupported
            })
        }

        $remainingCondition = [regex]::Replace($conditionText, $selectorPattern, '')
        $remainingCondition = $remainingCondition -replace '\s+|&&|[()]', ''
        $conditionSupported = [string]::IsNullOrWhiteSpace($conditionText) -or (
            ($selectorMatches.Count -gt 0) -and [string]::IsNullOrWhiteSpace($remainingCondition)
        )
        if ($conditionText -match '\|\|' -or $conditionText -match '(?i)COUNT\s*\(') { $conditionSupported = $false }
        if (@($selectors | Where-Object { -not $_.Supported }).Count -gt 0) { $conditionSupported = $false }

        $actionVerb = $null
        $outputType = $null
        $outputValue = $null
        $outputTypes = New-Object System.Collections.Generic.List[string]
        $actionKind = 'Unsupported'
        $actionSourceAlias = $null
        $attributeStore = $null
        $transformPattern = $null
        $transformReplacement = $null
        $invalidTransformRegex = $false
        $actionArguments = ''
        $actionSupported = $false
        $actionMatch = [regex]::Match($actionText, '(?is)=>\s*(?<verb>add|issue)\s*\((?<arguments>.*)\)\s*;?\s*$')
        if ($actionMatch.Success) {
            $actionVerb = $actionMatch.Groups['verb'].Value.ToLowerInvariant()
            $actionArguments = $actionMatch.Groups['arguments'].Value
            $typeMatch = [regex]::Match($actionArguments, '(?is)\bType\s*=\s*"(?<value>[^"]+)"')
            $valueLiteralMatch = [regex]::Match($actionArguments, '(?is)\bValue\s*=\s*"(?<value>[^"]*)"')
            $valueCopyMatch = [regex]::Match($actionArguments, '(?is)\bValue\s*=\s*(?<alias>[A-Za-z_][A-Za-z0-9_]*)\.Value\b')
            $passThroughMatch = [regex]::Match($actionArguments, '(?is)^\s*claim\s*=\s*(?<alias>[A-Za-z_][A-Za-z0-9_]*)\s*$')
            $storeMatch = [regex]::Match($actionArguments, '(?is)\bstore\s*=\s*"(?<value>[^"]+)"')
            $typesMatch = [regex]::Match($actionArguments, '(?is)\btypes\s*=\s*\((?<values>[^)]*)\)')
            $regexTransformMatch = [regex]::Match($actionArguments, '(?is)\bValue\s*=\s*RegExReplace\(\s*(?<alias>[A-Za-z_][A-Za-z0-9_]*)\.Value\s*,\s*"(?<pattern>(?:\\.|[^"])*)"\s*,\s*"(?<replacement>(?:\\.|[^"])*)"\s*\)')

            if ($typeMatch.Success) {
                $outputType = $typeMatch.Groups['value'].Value
                $outputTypes.Add($outputType)
            }
            if ($typesMatch.Success) {
                foreach ($quotedType in [regex]::Matches($typesMatch.Groups['values'].Value, '"(?<value>[^"]+)"')) {
                    if (-not $outputTypes.Contains($quotedType.Groups['value'].Value)) { $outputTypes.Add($quotedType.Groups['value'].Value) }
                }
            }
            if ($valueLiteralMatch.Success) { $outputValue = $valueLiteralMatch.Groups['value'].Value }
            if ($storeMatch.Success) { $attributeStore = $storeMatch.Groups['value'].Value }

            if ($passThroughMatch.Success) {
                $actionKind = 'PassThrough'
                $actionSourceAlias = $passThroughMatch.Groups['alias'].Value
                $sourceSelector = @($selectors | Where-Object Alias -ceq $actionSourceAlias | Select-Object -First 1)
                if ($sourceSelector.Count -eq 1) {
                    $sourceType = Get-SelectorClaimType -Selector $sourceSelector[0]
                    $outputTypes.Add($(if ($sourceType) { $sourceType } else { '*' }))
                    $actionSupported = $true
                }
            } elseif ($storeMatch.Success) {
                $actionKind = 'AttributeStore'
            } elseif ($regexTransformMatch.Success -and $typeMatch.Success) {
                $actionKind = 'RegexTransform'
                $actionSourceAlias = $regexTransformMatch.Groups['alias'].Value
                $transformPattern = $regexTransformMatch.Groups['pattern'].Value.Replace('\"', '"')
                $transformReplacement = $regexTransformMatch.Groups['replacement'].Value.Replace('\"', '"')
                try {
                    $null = [regex]::IsMatch('', $transformPattern, [Text.RegularExpressions.RegexOptions]::None, $script:RegexTimeout)
                } catch {
                    $invalidTransformRegex = $true
                }
                $actionSupported = -not $invalidTransformRegex -and @($selectors | Where-Object Alias -ceq $actionSourceAlias).Count -gt 0
            } elseif ($actionArguments -match '(?i)RegExReplace\s*\(') {
                $actionKind = 'RegexTransform'
            } elseif ($typeMatch.Success -and $valueCopyMatch.Success) {
                $actionKind = 'CopyClaimValue'
                $actionSourceAlias = $valueCopyMatch.Groups['alias'].Value
                $actionSupported = @($selectors | Where-Object Alias -ceq $actionSourceAlias).Count -gt 0
            } elseif ($typeMatch.Success -and $valueLiteralMatch.Success) {
                $actionKind = 'StaticClaim'
                $actionSupported = $true
            }
        }

        $inputClaimTypes = @($selectors | ForEach-Object { Get-SelectorClaimType -Selector $_ } | Where-Object { $_ } | Select-Object -Unique)

        $findings = New-Object System.Collections.Generic.List[object]
        if (-not $conditionSupported) {
            $findings.Add((New-RuleFinding -Severity Warning -Code 'UNSUPPORTED_CONDITION' -Message 'The condition uses syntax not evaluated by this version.'))
        }
        if (-not $actionSupported) {
            if ($actionKind -eq 'AttributeStore') {
                $findings.Add((New-RuleFinding -Severity Info -Code 'ATTRIBUTE_STORE_QUERY' -Message 'Input/output types are inventoried, but returned values require execution by the configured attribute store.'))
            } elseif ($actionKind -eq 'RegexTransform') {
                if ($invalidTransformRegex) {
                    $findings.Add((New-RuleFinding -Severity Warning -Code 'INVALID_REGEX_SYNTAX' -Message 'The RegExReplace pattern is not a valid .NET regular expression.'))
                } else {
                    $findings.Add((New-RuleFinding -Severity Info -Code 'UNSUPPORTED_REGEX_TRANSFORM' -Message 'The RegExReplace expression could not be parsed safely.'))
                }
            } else {
                $findings.Add((New-RuleFinding -Severity Info -Code 'UNSUPPORTED_ACTION' -Message 'The action is dynamic or could not be summarized.'))
            }
        }

        $hasProxy = @($selectors | Where-Object { -not $_.Negated -and (Test-SelectorTypeSuffix -Selector $_ -Suffix '/x-ms-proxy') }).Count -gt 0
        $negatesExternalLocation = @($selectors | Where-Object {
            if (-not $_.Negated -or -not (Test-SelectorTypeSuffix -Selector $_ -Suffix '/insidecorporatenetwork')) { return $false }
            $valuePredicate = @($_.Predicates | Where-Object Field -eq 'Value' | Select-Object -First 1)
            return $valuePredicate.Count -eq 1 -and $valuePredicate[0].Operator -eq '==' -and $valuePredicate[0].Expected -eq 'false'
        }).Count -gt 0
        $hasEndpoint = @($selectors | Where-Object { Test-SelectorTypeSuffix -Selector $_ -Suffix '/x-ms-endpoint-absolute-path' }).Count -gt 0
        $hasClientApplication = @($selectors | Where-Object { Test-SelectorTypeSuffix -Selector $_ -Suffix '/x-ms-client-application' }).Count -gt 0
        $hasUserAgent = @($selectors | Where-Object { Test-SelectorTypeSuffix -Selector $_ -Suffix '/x-ms-client-user-agent' }).Count -gt 0
        $hasGroup = @($selectors | Where-Object { Test-SelectorTypeSuffix -Selector $_ -Suffix '/groupsid' }).Count -gt 0

        if ($hasProxy -and $negatesExternalLocation) {
            $findings.Add((New-RuleFinding -Severity High -Code 'LIKELY_UNREACHABLE_WAP_RULE' -Message 'Requires x-ms-proxy while requiring insidecorporatenetwork=false to be absent.'))
        }
        if ($hasUserAgent) {
            $findings.Add((New-RuleFinding -Severity Warning -Code 'USER_AGENT_SIGNAL' -Message 'User-Agent is client-controlled and should not be the only security boundary.'))
        }
        if ($hasProxy -and $hasGroup -and -not $hasEndpoint -and -not $hasClientApplication -and -not $hasUserAgent) {
            $findings.Add((New-RuleFinding -Severity Warning -Code 'BROAD_EXTERNAL_GROUP_RULE' -Message 'WAP group exception is not restricted to an endpoint, protocol, or application.'))
        }

        $rules.Add([pscustomobject]@{
            RuleId                = "$RelyingParty::$RuleSetName::$ruleIndex"
            RelyingParty          = $RelyingParty
            Identifiers           = @($Identifiers)
            RuleSet               = $RuleSetName
            Index                 = $ruleIndex
            Name                  = $ruleName
            Text                  = $ruleBlock
            ConditionText         = $conditionText
            Conditions            = $selectors.ToArray()
            ConditionSupported    = $conditionSupported
            ActionVerb            = $actionVerb
            ActionKind            = $actionKind
            ActionSourceAlias     = $actionSourceAlias
            ActionArguments       = $actionArguments
            AttributeStore        = $attributeStore
            TransformPattern      = $transformPattern
            TransformReplacement  = $transformReplacement
            InputClaimTypes       = $inputClaimTypes
            OutputClaimTypes      = $outputTypes.ToArray()
            OutputClaimType       = $outputType
            OutputClaimValue      = $outputValue
            ActionSupported       = $actionSupported
            Findings              = $findings.ToArray()
        })
    }

    return $rules.ToArray()
}

function ConvertFrom-AdfsAccessControlPolicyAssignment {
    param([object]$RelyingParty)

    $policyName = ConvertTo-AdfsMeaningfulText -Value (Get-ObjectPropertyValue -InputObject $RelyingParty -Name 'AccessControlPolicyName')
    if ($policyName -cne 'Permit everyone') { return @() }

    return @([pscustomobject]@{
        RuleId                = "$($RelyingParty.Name)::AccessControlPolicy::1"
        RelyingParty          = [string]$RelyingParty.Name
        Identifiers           = @($RelyingParty.Identifier)
        RuleSet               = 'AccessControlPolicy'
        Index                 = 1
        Name                  = 'Access Control Policy: Permit everyone'
        Text                  = 'Permit everyone'
        ConditionText         = ''
        Conditions            = @()
        ConditionSupported    = $true
        ActionVerb            = 'issue'
        ActionKind            = 'StaticClaim'
        ActionSourceAlias     = $null
        ActionArguments       = 'Type = "http://schemas.microsoft.com/authorization/claims/permit", Value = "true"'
        AttributeStore        = $null
        TransformPattern      = $null
        TransformReplacement  = $null
        InputClaimTypes       = @()
        OutputClaimTypes      = @('http://schemas.microsoft.com/authorization/claims/permit')
        OutputClaimType       = 'http://schemas.microsoft.com/authorization/claims/permit'
        OutputClaimValue      = 'true'
        ActionSupported       = $true
        Findings              = @()
    })
}

function Test-TextPredicate {
    param(
        [AllowNull()][string]$Actual,
        [string]$Operator,
        [string]$Expected
    )

    if ($null -eq $Actual) { return $null }
    switch ($Operator) {
        '==' { return $Actual -ceq $Expected }
        '!=' { return $Actual -cne $Expected }
        '=~' {
            try { return [regex]::IsMatch($Actual, $Expected, [Text.RegularExpressions.RegexOptions]::None, $script:RegexTimeout) }
            catch { return $null }
        }
        '!~' {
            try { return -not [regex]::IsMatch($Actual, $Expected, [Text.RegularExpressions.RegexOptions]::None, $script:RegexTimeout) }
            catch { return $null }
        }
        default { return $null }
    }
}

function Get-ClaimFamily {
    param([AllowNull()][string]$ClaimType)
    if (-not $ClaimType) { return 'AllClaims' }
    if ($ClaimType -match '(?i)/requestcontext/claims/|/insidecorporatenetwork$') { return 'RequestContext' }
    return 'CallerClaims'
}

function Test-AdfsSelector {
    param(
        [object]$Selector,
        [object]$Transaction
    )

    if (-not $Selector.Supported) {
        return [pscustomobject]@{ Result = 'INDETERMINATE'; Evidence = 'Unsupported selector syntax.' }
    }

    if ($Selector.Body -eq '') {
        $claimsComplete = [bool]$Transaction.RequestContextComplete -and [bool]$Transaction.CallerClaimsComplete
        $potentialClaims = @(Get-ObjectPropertyValue -InputObject $Transaction -Name 'PotentialClaims')
        $positiveResult = if (@($Transaction.Claims).Count -gt 0) {
            'MATCH'
        } elseif (@($potentialClaims | Where-Object { $null -ne $_ }).Count -gt 0 -or -not $claimsComplete) {
            'INDETERMINATE'
        } else {
            'NO MATCH'
        }
        if ($Selector.Negated) {
            $positiveResult = switch ($positiveResult) {
                'MATCH'    { 'NO MATCH' }
                'NO MATCH' { 'MATCH' }
                default    { 'INDETERMINATE' }
            }
        }
        return [pscustomobject]@{ Result = $positiveResult; Evidence = "Any-claim selector result=$positiveResult." }
    }

    $typePredicate = @($Selector.Predicates | Where-Object Field -eq 'Type' | Select-Object -First 1)
    $claimType = if ($typePredicate.Count -eq 1 -and $typePredicate[0].Operator -eq '==') { $typePredicate[0].Expected } else { $null }
    $family = Get-ClaimFamily -ClaimType $claimType
    $familyComplete = switch ($family) {
        'RequestContext' { [bool]$Transaction.RequestContextComplete }
        'CallerClaims'   { [bool]$Transaction.CallerClaimsComplete }
        default          { [bool]$Transaction.RequestContextComplete -and [bool]$Transaction.CallerClaimsComplete }
    }

    $definiteMatch = $false
    $unknownCandidate = $false
    $observedValues = New-Object System.Collections.Generic.List[string]

    foreach ($claim in @($Transaction.Claims)) {
        $claimMatches = $true
        $claimUnknown = $false
        foreach ($predicate in $Selector.Predicates) {
            $actualValue = Get-ObjectPropertyValue -InputObject $claim -Name $predicate.Field
            $predicateResult = Test-TextPredicate -Actual $actualValue -Operator $predicate.Operator -Expected $predicate.Expected
            if ($null -eq $predicateResult) { $claimUnknown = $true }
            elseif (-not $predicateResult) { $claimMatches = $false; break }
        }
        if ($claimType -and $claim.Type -ceq $claimType) { $observedValues.Add([string]$claim.Value) }
        if ($claimMatches -and -not $claimUnknown) { $definiteMatch = $true; break }
        if ($claimMatches -and $claimUnknown) { $unknownCandidate = $true }
    }

    $potentialClaims = Get-ObjectPropertyValue -InputObject $Transaction -Name 'PotentialClaims'
    foreach ($claim in @($potentialClaims | Where-Object { $null -ne $_ })) {
        $potentialMatch = $true
        foreach ($predicate in $Selector.Predicates) {
            $actualValue = Get-ObjectPropertyValue -InputObject $claim -Name $predicate.Field
            $predicateResult = Test-TextPredicate -Actual $actualValue -Operator $predicate.Operator -Expected $predicate.Expected
            if ($null -ne $predicateResult -and -not $predicateResult) {
                $potentialMatch = $false
                break
            }
        }
        if ($potentialMatch) { $unknownCandidate = $true; break }
    }

    $positiveResult = if ($definiteMatch) { 'MATCH' } elseif ($unknownCandidate -or -not $familyComplete) { 'INDETERMINATE' } else { 'NO MATCH' }
    $finalResult = $positiveResult
    if ($Selector.Negated) {
        $finalResult = switch ($positiveResult) {
            'MATCH'    { 'NO MATCH' }
            'NO MATCH' { 'MATCH' }
            default    { 'INDETERMINATE' }
        }
    }

    $selectorDescription = if ($claimType) { $claimType.Split('/')[-1] } else { $Selector.Body }
    $expectation = if ($Selector.Negated) { 'absent' } else { 'present/matching' }
    $observedText = if ($observedValues.Count -gt 0) { " observed=[$($observedValues -join ', ')]" } else { '' }
    [pscustomobject]@{
        Result   = $finalResult
        Evidence = "$selectorDescription expected=$expectation;$observedText result=$finalResult"
    }
}

function Test-AdfsRuleForTransaction {
    param(
        [object]$Rule,
        [object]$Transaction
    )

    if (-not $Rule.ConditionSupported) {
        return [pscustomobject]@{ Result = 'INDETERMINATE'; Confidence = 'Unsupported'; Evidence = 'Unsupported rule condition.' }
    }

    $conditionResults = New-Object System.Collections.Generic.List[object]
    foreach ($selector in @($Rule.Conditions)) {
        $conditionResults.Add((Test-AdfsSelector -Selector $selector -Transaction $Transaction))
    }

    $result = if (@($conditionResults | Where-Object Result -eq 'NO MATCH').Count -gt 0) {
        'NO MATCH'
    } elseif (@($conditionResults | Where-Object Result -eq 'INDETERMINATE').Count -gt 0) {
        'INDETERMINATE'
    } else {
        'MATCH'
    }

    [pscustomobject]@{
        Result     = $result
        Confidence = if ($result -eq 'INDETERMINATE') { 'Partial' } else { 'Complete' }
        Evidence   = (@($conditionResults.Evidence) -join ' | ')
    }
}

function Get-AdfsClaimsForAlias {
    param(
        [object]$Rule,
        [object]$Transaction,
        [string]$Alias
    )

    $selector = @($Rule.Conditions | Where-Object Alias -ceq $Alias | Select-Object -First 1)
    if ($selector.Count -ne 1 -or $selector[0].Negated) { return @() }

    return @($Transaction.Claims | Where-Object {
        $claim = $_
        foreach ($predicate in $selector[0].Predicates) {
            $actualValue = Get-ObjectPropertyValue -InputObject $claim -Name $predicate.Field
            $predicateResult = Test-TextPredicate -Actual $actualValue -Operator $predicate.Operator -Expected $predicate.Expected
            if ($null -eq $predicateResult -or -not $predicateResult) { return $false }
        }
        return $true
    })
}

function Get-AdfsProducedClaims {
    param(
        [object]$Rule,
        [object]$Transaction
    )

    switch ($Rule.ActionKind) {
        'StaticClaim' {
            return @([pscustomobject]@{
                Type = $Rule.OutputClaimType; Value = $Rule.OutputClaimValue
                Issuer = $null; OriginalIssuer = $null; ValueType = $null
                Source = "Rule $($Rule.Index): $($Rule.Name)"
            })
        }
        'PassThrough' {
            return @(Get-AdfsClaimsForAlias -Rule $Rule -Transaction $Transaction -Alias $Rule.ActionSourceAlias | ForEach-Object {
                [pscustomobject]@{
                    Type = $_.Type; Value = $_.Value; Issuer = $_.Issuer
                    OriginalIssuer = $_.OriginalIssuer; ValueType = $_.ValueType
                    Source = "Rule $($Rule.Index): $($Rule.Name)"
                }
            })
        }
        'CopyClaimValue' {
            return @(Get-AdfsClaimsForAlias -Rule $Rule -Transaction $Transaction -Alias $Rule.ActionSourceAlias | ForEach-Object {
                [pscustomobject]@{
                    Type = $Rule.OutputClaimType; Value = $_.Value; Issuer = $null
                    OriginalIssuer = $null; ValueType = $_.ValueType
                    Source = "Rule $($Rule.Index): $($Rule.Name)"
                }
            })
        }
        'RegexTransform' {
            return @(Get-AdfsClaimsForAlias -Rule $Rule -Transaction $Transaction -Alias $Rule.ActionSourceAlias | ForEach-Object {
                try {
                    $transformedValue = [regex]::Replace(
                        [string]$_.Value,
                        [string]$Rule.TransformPattern,
                        [string]$Rule.TransformReplacement,
                        [Text.RegularExpressions.RegexOptions]::None,
                        $script:RegexTimeout
                    )
                    [pscustomobject]@{
                        Type = $Rule.OutputClaimType; Value = $transformedValue; Issuer = $null
                        OriginalIssuer = $null; ValueType = $_.ValueType
                        Source = "Rule $($Rule.Index): $($Rule.Name)"
                    }
                } catch {
                    Write-Verbose "Regex transform failed for rule '$($Rule.Name)': $($_.Exception.Message)"
                }
            })
        }
        default { return @() }
    }
}

function Get-AdfsOutputObservation {
    param(
        [object]$Rule,
        [object]$Transaction,
        [string]$EvaluationResult,
        [object[]]$ProducedClaims
    )

    if ($Rule.RuleSet -ne 'IssuanceTransformRules' -or $EvaluationResult -eq 'NO MATCH') { return 'N/A' }
    if ($Rule.ActionVerb -eq 'add') { return 'INTERNAL ONLY' }
    if (-not [bool](Get-ObjectPropertyValue -InputObject $Transaction -Name 'OutputClaimsComplete')) { return 'UNKNOWN' }

    $expectedTypes = @($ProducedClaims.Type | Where-Object { $_ } | Select-Object -Unique)
    if ($expectedTypes.Count -eq 0) {
        $expectedTypes = @($Rule.OutputClaimTypes | Where-Object { $_ -and $_ -ne '*' } | Select-Object -Unique)
    }
    if ($expectedTypes.Count -eq 0) { return 'UNKNOWN' }

    $observedTypes = @($Transaction.OutputClaims.Type | Where-Object { $_ } | Select-Object -Unique)
    $matchedCount = @($expectedTypes | Where-Object { $expectedType = $_; @($observedTypes | Where-Object { $_ -ceq $expectedType }).Count -gt 0 }).Count
    if ($matchedCount -eq $expectedTypes.Count) { return 'ALL TYPES OBSERVED' }
    if ($matchedCount -gt 0) { return 'PARTIAL' }
    return 'NONE'
}

function Invoke-AdfsRuleSetEvaluation {
    param(
        [object[]]$Rules,
        [object]$Transaction,
        [ValidateSet('Authorization', 'IssuanceTransform')]
        [string]$EvaluationMode = 'Authorization'
    )

    $workingTransaction = [pscustomobject]@{
        ActivityId             = $Transaction.ActivityId
        RequestContextComplete = [bool]$Transaction.RequestContextComplete
        CallerClaimsComplete   = [bool]$Transaction.CallerClaimsComplete
        Claims                 = @($Transaction.Claims)
        PotentialClaims        = @()
    }
    $evaluations = New-Object System.Collections.Generic.List[object]
    $issuedAuthorizationClaims = New-Object System.Collections.Generic.List[object]
    $potentialAuthorizationClaims = New-Object System.Collections.Generic.List[object]
    $unsupportedActionCouldAffectDecision = $false

    foreach ($rule in @($Rules | Sort-Object Index)) {
        $evaluation = Test-AdfsRuleForTransaction -Rule $rule -Transaction $workingTransaction
        $producedClaims = if ($rule.ActionSupported) { @(Get-AdfsProducedClaims -Rule $rule -Transaction $workingTransaction) } else { @() }
        $outputObserved = Get-AdfsOutputObservation -Rule $rule -Transaction $Transaction -EvaluationResult $evaluation.Result -ProducedClaims $producedClaims
        $evaluations.Add([pscustomobject]@{
            Time         = $Transaction.Time
            ActivityId   = $Transaction.ActivityId
            User         = $Transaction.User
            RelyingParty = $rule.RelyingParty
            ActualResult = $Transaction.ActualResult
            RuleId       = $rule.RuleId
            RuleSet      = $rule.RuleSet
            RuleIndex    = $rule.Index
            RuleName     = $rule.Name
            Result       = $evaluation.Result
            Confidence   = $evaluation.Confidence
            Action       = $rule.ActionVerb
            ActionKind   = $rule.ActionKind
            InputClaims  = @($rule.InputClaimTypes) -join ' | '
            OutputClaimTypes = @($rule.OutputClaimTypes) -join ' | '
            AttributeStore = $rule.AttributeStore
            OutputObserved = $outputObserved
            Evidence     = $evaluation.Evidence
        })

        if (-not $rule.ActionSupported) {
            if ($evaluation.Result -ne 'NO MATCH') { $unsupportedActionCouldAffectDecision = $true }
            if ($evaluation.Result -ne 'NO MATCH') {
                foreach ($potentialType in @($rule.OutputClaimTypes | Where-Object { $_ -and $_ -ne '*' })) {
                    $potentialClaim = [pscustomobject]@{
                        Type = $potentialType; Value = $null; Issuer = $null
                        OriginalIssuer = $null; ValueType = $null
                        Source = "Potential output of rule $($rule.Index): $($rule.Name)"
                    }
                    $workingTransaction.PotentialClaims = @($workingTransaction.PotentialClaims) + $potentialClaim
                }
            }
            continue
        }
        if ($evaluation.Result -eq 'MATCH') {
            foreach ($producedClaim in $producedClaims) {
                $workingTransaction.Claims = @($workingTransaction.Claims) + $producedClaim
                if ($rule.ActionVerb -eq 'issue' -and $producedClaim.Type -match '/authorization/claims/(?:permit|deny)$') {
                    $issuedAuthorizationClaims.Add($producedClaim)
                }
            }
        } elseif ($evaluation.Result -eq 'INDETERMINATE') {
            foreach ($potentialType in @($rule.OutputClaimTypes | Where-Object { $_ -and $_ -ne '*' })) {
                $potentialClaim = [pscustomobject]@{
                    Type = $potentialType; Value = $null; Issuer = $null
                    OriginalIssuer = $null; ValueType = $null
                    Source = "Potential output of rule $($rule.Index): $($rule.Name)"
                }
                $workingTransaction.PotentialClaims = @($workingTransaction.PotentialClaims) + $potentialClaim
                if ($rule.ActionVerb -eq 'issue' -and $potentialClaim.Type -match '/authorization/claims/(?:permit|deny)$') {
                    $potentialAuthorizationClaims.Add($potentialClaim)
                }
            }
        }
    }

    $hasDeny = @($issuedAuthorizationClaims | Where-Object { $_.Type -match '/deny$' }).Count -gt 0
    $hasPermit = @($issuedAuthorizationClaims | Where-Object { $_.Type -match '/permit$' }).Count -gt 0
    $mayDeny = @($potentialAuthorizationClaims | Where-Object { $_.Type -match '/deny$' }).Count -gt 0
    $mayPermit = @($potentialAuthorizationClaims | Where-Object { $_.Type -match '/permit$' }).Count -gt 0

    $decision = if ($EvaluationMode -eq 'IssuanceTransform') {
        'NOT APPLICABLE'
    } elseif ($hasDeny) {
        'DENY'
    } elseif ($mayDeny -or $unsupportedActionCouldAffectDecision) {
        'INDETERMINATE'
    } elseif ($hasPermit) {
        'PERMIT'
    } elseif ($mayPermit) {
        'INDETERMINATE'
    } else {
        'DENY'
    }

    [pscustomobject]@{
        Decision          = $decision
        Evaluations       = $evaluations.ToArray()
        FinalClaims       = @($workingTransaction.Claims)
        PotentialClaims   = @($workingTransaction.PotentialClaims)
    }
}

function New-ClaimBag {
    [pscustomobject]@{
        Claims                 = New-Object System.Collections.Generic.List[object]
        RequestContextComplete = $false
        CallerClaimsComplete   = $false
    }
}

function Add-ObservedClaim {
    param(
        [Parameter(Mandatory)][object]$ClaimBag,
        [AllowNull()][string]$Type,
        [AllowNull()][string]$Value,
        [string]$Source,
        [AllowNull()][string]$Issuer,
        [AllowNull()][string]$OriginalIssuer,
        [AllowNull()][string]$ValueType
    )

    if ([string]::IsNullOrWhiteSpace($Type) -or [string]::IsNullOrWhiteSpace($Value) -or $Value -eq '-') { return }
    $duplicate = @($ClaimBag.Claims | Where-Object {
        $_.Type -ceq $Type -and $_.Value -ceq $Value -and $_.Source -ceq $Source
    }).Count -gt 0
    if ($duplicate) { return }

    $ClaimBag.Claims.Add([pscustomobject]@{
        Type           = $Type
        Value          = $Value
        Issuer         = $Issuer
        OriginalIssuer = $OriginalIssuer
        ValueType      = $ValueType
        Source         = $Source
    })
}

function Get-EventPropertyValues {
    param([Parameter(Mandatory)][object]$EventRecord)

    $values = New-Object System.Collections.Generic.List[object]
    foreach ($property in @($EventRecord.Properties)) {
        if ($null -ne $property -and $property.PSObject.Properties['Value']) {
            $values.Add($property.Value)
        } else {
            $values.Add($property)
        }
    }
    return $values.ToArray()
}

function Get-GuidFromValue {
    param([AllowNull()][object]$Value)

    if ($null -eq $Value) { return $null }
    $match = [regex]::Match([string]$Value, '(?i)(?<guid>[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})')
    if ($match.Success) { return $match.Groups['guid'].Value.ToLowerInvariant() }
    return $null
}

function Get-EventActivityId {
    param([Parameter(Mandatory)][object]$EventRecord)

    $activityProperty = $EventRecord.PSObject.Properties['ActivityId']
    if ($activityProperty -and $activityProperty.Value) {
        $activityId = Get-GuidFromValue -Value $activityProperty.Value
        if ($activityId) { return $activityId }
    }

    try {
        $eventXml = $EventRecord.ToXml()
        $xmlMatch = [regex]::Match($eventXml, '(?i)<Correlation[^>]+ActivityID="\{?(?<guid>[0-9a-f-]{36})\}?"')
        if ($xmlMatch.Success) { return $xmlMatch.Groups['guid'].Value.ToLowerInvariant() }
    } catch {
        Write-Verbose "Unable to read event XML for Activity ID correlation: $($_.Exception.Message)"
    }

    $message = [string](Get-ObjectPropertyValue -InputObject $EventRecord -Name 'Message')
    $messageMatch = [regex]::Match($message, '(?im)Activity\s*ID\s*:\s*\{?(?<guid>[0-9a-f-]{36})\}?')
    if ($messageMatch.Success) { return $messageMatch.Groups['guid'].Value.ToLowerInvariant() }
    return $null
}

function Get-EventInstanceId {
    param([Parameter(Mandatory)][object]$EventRecord)

    $propertyValues = @(Get-EventPropertyValues -EventRecord $EventRecord)
    if ($propertyValues.Count -gt 0) { return Get-GuidFromValue -Value $propertyValues[0] }
    return $null
}

function Test-IsClaimTypeUri {
    param([AllowNull()][string]$Value)

    if ([string]::IsNullOrWhiteSpace($Value)) { return $false }
    $uri = $null
    if (-not [uri]::TryCreate($Value, [UriKind]::Absolute, [ref]$uri)) { return $false }
    return $uri.Scheme -in @('http', 'https', 'urn')
}

function Add-PairedClaimsFromEvent {
    param(
        [Parameter(Mandatory)][object]$EventRecord,
        [Parameter(Mandatory)][object]$ClaimBag,
        [string]$Source
    )

    $propertyValues = @(Get-EventPropertyValues -EventRecord $EventRecord)
    $firstClaimTypeIndex = $null
    for ($propertyIndex = 0; $propertyIndex -lt ($propertyValues.Count - 1); $propertyIndex++) {
        if (Test-IsClaimTypeUri -Value ([string]$propertyValues[$propertyIndex])) {
            $firstClaimTypeIndex = $propertyIndex
            break
        }
    }

    if ($null -eq $firstClaimTypeIndex) { return }
    for ($propertyIndex = $firstClaimTypeIndex; $propertyIndex -lt ($propertyValues.Count - 1); $propertyIndex += 2) {
        $possibleType = [string]$propertyValues[$propertyIndex]
        if (Test-IsClaimTypeUri -Value $possibleType) {
            Add-ObservedClaim -ClaimBag $ClaimBag -Type $possibleType -Value ([string]$propertyValues[$propertyIndex + 1]) -Source $Source
        }
    }
}

function Add-RequestContextFromEvent410 {
    param(
        [Parameter(Mandatory)][object]$EventRecord,
        [Parameter(Mandatory)][object]$ClaimBag
    )

    $message = [string](Get-ObjectPropertyValue -InputObject $EventRecord -Name 'Message')
    $headerMap = [ordered]@{
        'X-MS-Client-Application'     = $script:ClaimTypes.ClientApplication
        'X-MS-Client-User-Agent'      = $script:ClaimTypes.ClientUserAgent
        'X-MS-Endpoint-Absolute-Path' = $script:ClaimTypes.EndpointPath
        'X-MS-Forwarded-Client-IP'    = $script:ClaimTypes.ForwardedClientIp
        'X-MS-Proxy'                  = $script:ClaimTypes.Proxy
        'X-MS-ADFS-Proxy-Client-IP'   = $script:ClaimTypes.ProxyClientIp
    }

    $messageClaimTypes = @{}
    foreach ($headerName in $headerMap.Keys) {
        $headerMatch = [regex]::Match($message, '(?im)^\s*' + [regex]::Escape($headerName) + '\s*:\s*(?<value>[^\r\n]*)')
        if ($headerMatch.Success) {
            Add-ObservedClaim -ClaimBag $ClaimBag -Type $headerMap[$headerName] -Value $headerMatch.Groups['value'].Value.Trim() -Source 'Event 410'
            $messageClaimTypes[$headerMap[$headerName]] = $true
        }
    }

    # Stable property order on AD FS 2016+ provides a locale-independent path.
    $propertyValues = @(Get-EventPropertyValues -EventRecord $EventRecord)
    if ($propertyValues.Count -ge 8) {
        $propertyMap = @(
            [pscustomobject]@{ Index = 1; Type = $script:ClaimTypes.ClientApplication }
            [pscustomobject]@{ Index = 2; Type = $script:ClaimTypes.ClientUserAgent }
            [pscustomobject]@{ Index = 4; Type = $script:ClaimTypes.EndpointPath }
            [pscustomobject]@{ Index = 5; Type = $script:ClaimTypes.ForwardedClientIp }
            [pscustomobject]@{ Index = 6; Type = $script:ClaimTypes.Proxy }
            [pscustomobject]@{ Index = 7; Type = $script:ClaimTypes.ProxyClientIp }
        )
        foreach ($propertyMapping in $propertyMap) {
            $claimType = $propertyMapping.Type
            if (-not $messageClaimTypes.ContainsKey($claimType)) {
                Add-ObservedClaim -ClaimBag $ClaimBag -Type $claimType -Value ([string]$propertyValues[$propertyMapping.Index]) -Source 'Event 410'
            }
        }
    }
    $ClaimBag.RequestContextComplete = $true
}

function Get-PreferredClaimValue {
    param(
        [object]$ClaimBag,
        [string[]]$TypeSuffixes
    )

    foreach ($typeSuffix in $TypeSuffixes) {
        $claim = @($ClaimBag.Claims | Where-Object {
            $_.Type.EndsWith($typeSuffix, [System.StringComparison]::OrdinalIgnoreCase)
        } | Select-Object -First 1)
        if ($claim.Count -eq 1) { return $claim[0].Value }
    }
    return $null
}

function ConvertTo-AdfsTransactions {
    param([object[]]$Events)

    if (-not $Events) { return @() }
    $eventWrappers = New-Object System.Collections.Generic.List[object]
    $instanceToActivity = @{}

    foreach ($eventRecord in $Events) {
        $activityId = Get-EventActivityId -EventRecord $eventRecord
        $instanceId = Get-EventInstanceId -EventRecord $eventRecord
        if ($activityId -and $instanceId -and $eventRecord.Id -in $script:InstanceAnchorEventIds) {
            $instanceToActivity[$instanceId] = $activityId
        }
        $eventWrappers.Add([pscustomobject]@{ Event = $eventRecord; ActivityId = $activityId; InstanceId = $instanceId })
    }

    foreach ($eventWrapper in $eventWrappers) {
        if (-not $eventWrapper.ActivityId -and $eventWrapper.InstanceId -and $instanceToActivity.ContainsKey($eventWrapper.InstanceId)) {
            $eventWrapper.ActivityId = $instanceToActivity[$eventWrapper.InstanceId]
        }
    }

    $transactions = New-Object System.Collections.Generic.List[object]
    foreach ($eventGroup in @($eventWrappers | Where-Object ActivityId | Group-Object ActivityId)) {
        $transactionEvents = @($eventGroup.Group.Event | Sort-Object TimeCreated, RecordId)
        $claimBag = New-ClaimBag
        $outputClaims = New-Object System.Collections.Generic.List[object]
        $relyingParty = $null
        $user = $null
        $clientIp = $null
        $userAgent = $null
        $endpoint = $null
        $throughProxy = $null
        $proxyName = $null
        $actualResult = 'UNKNOWN'
        $outputClaimsComplete = $false

        foreach ($eventRecord in $transactionEvents) {
            $propertyValues = @(Get-EventPropertyValues -EventRecord $eventRecord)
            $message = [string](Get-ObjectPropertyValue -InputObject $eventRecord -Name 'Message')
            switch ([int]$eventRecord.Id) {
                403 {
                    if ($propertyValues.Count -ge 16) {
                        if (-not $clientIp) { $clientIp = ConvertTo-AdfsMeaningfulText -Value $propertyValues[3] }
                        if (-not $endpoint) { $endpoint = ConvertTo-AdfsMeaningfulText -Value $propertyValues[5] }
                        if (-not $userAgent) { $userAgent = ConvertTo-AdfsMeaningfulText -Value $propertyValues[9] }
                        if (-not $user) { $user = ConvertTo-AdfsMeaningfulText -Value $propertyValues[11] }
                        if (-not $relyingParty) { $relyingParty = ConvertTo-AdfsMeaningfulText -Value $propertyValues[13] }
                        $throughProxy = ([string]$propertyValues[14]) -match '^(?i:true|1)$'
                        $proxyName = ConvertTo-AdfsMeaningfulText -Value $propertyValues[15]
                    }
                }
                410 { Add-RequestContextFromEvent410 -EventRecord $eventRecord -ClaimBag $claimBag }
                412 {
                    if ($propertyValues.Count -ge 4 -and -not $relyingParty) {
                        $relyingParty = ConvertTo-AdfsMeaningfulText -Value $propertyValues[3]
                    }
                }
                501 {
                    Add-PairedClaimsFromEvent -EventRecord $eventRecord -ClaimBag $claimBag -Source 'Event 501 caller claims'
                    $claimBag.CallerClaimsComplete = $true
                }
                500 {
                    $outputBag = New-ClaimBag
                    Add-PairedClaimsFromEvent -EventRecord $eventRecord -ClaimBag $outputBag -Source 'Event 500 issued claims'
                    foreach ($claim in $outputBag.Claims) { $outputClaims.Add($claim) }
                    $outputClaimsComplete = $true
                }
                299 {
                    if ($actualResult -eq 'UNKNOWN') { $actualResult = 'SUCCESS' }
                    if ($propertyValues.Count -ge 3 -and -not $relyingParty) {
                        $relyingParty = ConvertTo-AdfsMeaningfulText -Value $propertyValues[2]
                    }
                }
                324  { $actualResult = 'DENY' }
                1200 { if ($actualResult -eq 'UNKNOWN') { $actualResult = 'SUCCESS' } }
                1201 { if ($actualResult -ne 'DENY') { $actualResult = 'FAILURE' } }
                1202 { if ($actualResult -eq 'UNKNOWN') { $actualResult = 'SUCCESS' } }
                1203 { if ($actualResult -ne 'DENY') { $actualResult = 'FAILURE' } }
            }

            if (-not $relyingParty -and $message) {
                $rpMatch = [regex]::Match($message, '(?im)^\s*(?:Relying party|Targeted relying party)\s*:\s*(?<value>[^\r\n]+)')
                if ($rpMatch.Success) { $relyingParty = ConvertTo-AdfsMeaningfulText -Value $rpMatch.Groups['value'].Value }
            }
        }

        $proxyClaims = @($claimBag.Claims | Where-Object { $_.Type.EndsWith('/x-ms-proxy', [System.StringComparison]::OrdinalIgnoreCase) })
        if ($null -eq $throughProxy -and $claimBag.RequestContextComplete) { $throughProxy = $proxyClaims.Count -gt 0 }
        if ($throughProxy -eq $true) {
            if ($proxyClaims.Count -eq 0) {
                $observedProxy = if ($proxyName -and $proxyName -ne '-') { $proxyName } else { '<present>' }
                Add-ObservedClaim -ClaimBag $claimBag -Type $script:ClaimTypes.Proxy -Value $observedProxy -Source 'Event 403'
            }
            Add-ObservedClaim -ClaimBag $claimBag -Type $script:ClaimTypes.InsideNetwork -Value 'false' -Source 'Derived from WAP path'
        } elseif ($throughProxy -eq $false) {
            Add-ObservedClaim -ClaimBag $claimBag -Type $script:ClaimTypes.InsideNetwork -Value 'true' -Source 'Derived from direct AD FS path'
        }

        if (-not $user) { $user = Get-PreferredClaimValue -ClaimBag $claimBag -TypeSuffixes @('/upn', '/windowsaccountname', '/name') }
        $claimRelyingParty = Get-PreferredClaimValue -ClaimBag $claimBag -TypeSuffixes @('/relyingpartytrustid')
        if ($claimRelyingParty) { $relyingParty = $claimRelyingParty }
        if (-not $userAgent) { $userAgent = Get-PreferredClaimValue -ClaimBag $claimBag -TypeSuffixes @('/x-ms-client-user-agent') }
        if (-not $endpoint) { $endpoint = Get-PreferredClaimValue -ClaimBag $claimBag -TypeSuffixes @('/x-ms-endpoint-absolute-path') }

        $transactions.Add([pscustomobject]@{
            ActivityId             = $eventGroup.Name
            Time                   = ($transactionEvents | Select-Object -First 1).TimeCreated
            Server                 = (@($transactionEvents | Select-Object -ExpandProperty MachineName -Unique) -join ' | ')
            User                   = $user
            RelyingParty           = $relyingParty
            ClientIp               = $clientIp
            UserAgent              = $userAgent
            Endpoint               = $endpoint
            ThroughProxy           = $throughProxy
            ProxyName              = $proxyName
            ActualResult           = $actualResult
            EventIds               = @($transactionEvents.Id | Sort-Object -Unique)
            Claims                 = $claimBag.Claims.ToArray()
            OutputClaims           = $outputClaims.ToArray()
            OutputClaimsComplete   = $outputClaimsComplete
            RequestContextComplete = [bool]$claimBag.RequestContextComplete
            CallerClaimsComplete   = [bool]$claimBag.CallerClaimsComplete
        })
    }
    return $transactions.ToArray()
}

function Get-AdfsAuditEvents {
    param(
        [string[]]$Servers,
        [string[]]$Paths,
        [datetime]$StartTime
    )

    $events = New-Object System.Collections.Generic.List[object]
    foreach ($path in @($Paths | Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_) })) {
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Event log not found: $path" }
        Write-Info "Reading exported event log: $path"
        $records = Get-WinEvent -Path $path -Oldest -ErrorAction Stop | Where-Object {
            $_.ProviderName -eq 'AD FS Auditing' -and $_.Id -in $script:AuditEventIds -and $_.TimeCreated -ge $StartTime
        }
        foreach ($record in @($records)) { $events.Add($record) }
    }

    foreach ($server in @($Servers | Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_) })) {
        try {
            Write-Info "Reading AD FS Auditing from $server"
            $filter = @{ LogName = 'Security'; ProviderName = 'AD FS Auditing'; Id = $script:AuditEventIds; StartTime = $StartTime }
            $serverShortName = ([string]$server -split '\.')[0]
            $isLocalServer = $serverShortName -ieq $env:COMPUTERNAME -or $server -ieq 'localhost' -or $server -eq '.'
            $records = if ($isLocalServer) {
                Get-WinEvent -FilterHashtable $filter -ErrorAction Stop
            } else {
                Get-WinEvent -ComputerName $server -FilterHashtable $filter -ErrorAction Stop
            }
            foreach ($record in @($records)) { $events.Add($record) }
            Write-Ok "${server}: $(@($records).Count) audit event(s)"
