function ConvertTo-AdfsMeaningfulText {
    param([AllowNull()][object]$Value)

    if ($null -eq $Value) { return $null }
    $text = ([string]$Value).Trim()
    if ([string]::IsNullOrWhiteSpace($text) -or $text -in @('-', '<null>', 'N/A')) { return $null }
    return $text
}

function Split-AdfsRuleSet {
    param([AllowNull()][string]$RuleSet)

    if ([string]::IsNullOrWhiteSpace($RuleSet)) { return @() }

    $lines = $RuleSet -split "`r?`n"
    $blocks = New-Object System.Collections.Generic.List[string]
    $current = New-Object System.Text.StringBuilder
    $previousNonBlankWasTemplate = $false

    foreach ($line in $lines) {
        $trimmed = $line.Trim()
        $isTemplate = $trimmed -match '^@RuleTemplate\s*='
        $isName = $trimmed -match '^@RuleName\s*='
        $startsRule = $isTemplate -or ($isName -and -not $previousNonBlankWasTemplate)

        if ($startsRule -and $current.Length -gt 0) {
            $block = $current.ToString().Trim()
            if ($block) { $blocks.Add($block) }
            $null = $current.Clear()
        }

        $null = $current.AppendLine($line)
        if ($trimmed) { $previousNonBlankWasTemplate = $isTemplate }
    }

    if ($current.Length -gt 0) {
        $block = $current.ToString().Trim()
        if ($block) { $blocks.Add($block) }
    }

    if ($blocks.Count -eq 0) { $blocks.Add($RuleSet.Trim()) }
    return @($blocks)
}

